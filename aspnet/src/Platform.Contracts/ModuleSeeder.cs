namespace Platform.Contracts;

// ======================================================================
// فاز ۶۲ — سیدِ داده‌های اولیهٔ ماژول‌ها (درخواست کاربر):
// «وقتی داده‌های اولیه به دیتابیس اضافه می‌شوند، در همان مرحلهٔ اولین اجرا،
// هر ماژول اطلاعات خودش را — در صورت وجود — بریزد توی دیتابیس.»
// ----------------------------------------------------------------------
// قانون معماری: هر ماژول کلاس Seeder خودش را در لایهٔ دیتای همین ماژول
// (HrModules.*.Data) پیاده می‌کند و فقط از DbContext خودش + قراردادهای
// همین پروژه + دادهٔ پایه (HrBaseDbContext) استفاده می‌کند — هیچ ارجاع
// مستقیم بین ماژول‌ها. هاست (نقش ترکیب) در اولین اجرا — هم بوت عادی و
// هم ویزارد راه‌اندازی اولیه — همهٔ IModuleSeederها را به ترتیب Order
// اجرا می‌کند. اجرای سید باید «خودترمیم» (idempotent) باشد: در هر بوت
// بررسی شود و فقط داده‌های غایب ساخته شوند، بدون ساخت دادهٔ تکراری.
// ======================================================================

/// <summary>سیدِ داده‌های اولیهٔ یک ماژول — هاست آن را در اولین اجرا و هر بوت (خودترمیم) فرامی‌خواند.</summary>
public interface IModuleSeeder
{
    /// <summary>کد ماژول (attendance/access/visitors/payroll/parking) — برای لاگ و ردیابی.</summary>
    string ModuleCode { get; }

    /// <summary>ترتیب اجرا میان ماژول‌ها (کوچک‌تر = زودتر). سیدهای وابسته به دادهٔ سایر ماژول‌ها باید Order بزرگ‌تری بگیرند.</summary>
    int Order => 100;

    /// <summary>
    /// ریختن داده‌های اولیهٔ ماژول.
    /// <paramref name="scopedServices"/>: Provider اسکوپ جاری — DbContext ماژول/پایه و قراردادها از همین گرفته می‌شود.
    /// <paramref name="demoData"/>: پرچم «دادهٔ نمایشی» (SeedDemo) — بخش‌های نمایشی اختیاری می‌توانند به آن احترام بگذارند؛
    /// بخش‌های پیکربندیِ الزامی ماژول باید همیشه (مستقل از این پرچم) خودترمیم شوند.
    /// </summary>
    Task SeedAsync(IServiceProvider scopedServices, bool demoData, CancellationToken ct = default);
}
