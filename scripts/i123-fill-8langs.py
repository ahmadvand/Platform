total_add = 0
for code, tbl in T.items():
    pp = f"{PACKS}/hr-lang-{code}.json"
    pack = json.load(open(pp, encoding="utf-8"))
    add = {k: v for k, v in tbl.items() if pack["entries"].get(k) != v}
    pack["entries"].update(add)
    json.dump(pack, open(pp, "w", encoding="utf-8"), ensure_ascii=False, indent=0)
    total_add += len(add)
    print(f"[{code}] +{len(add)} pack={len(pack['entries'])}")

