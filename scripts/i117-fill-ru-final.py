# --- اعتبارسنجی: placeholder ها، گویله‌ها و ایموجی باید حفظ شوند ---
import re
bad = []
for k, v in T.items():
    kp = sorted(re.findall(r"\{\d+\}", k))
    vp = sorted(re.findall(r"\{\d+\}", v))
    if kp != vp:
        bad.append(("placeholder", k[:50]))
    for ch in ("«", "»", "⚠", "🖧", "🛠", "…"):
        if ch in k and ch not in v:
            bad.append((f"lost {ch}", k[:50]))
    if not v.strip():
        bad.append(("empty", k[:50]))
print("validation:", "OK" if not bad else bad)
