# ---------- ۱) packs را بازسازی (ادغام EXTRA با ترجمه‌های موجود) ----------
LANGS = [("prs","دری","rtl"),("ps","پښتو","rtl"),("ka","ქართული","ltr"),
         ("ky","Кыргызча","ltr"),("uz","Oʻzbekcha","ltr"),("tg","Тоҷикӣ","ltr"),("tk","Türkmençe","ltr")]
total = 0
for code, title, d in LANGS:
    p = os.path.join(OUT, f"hr-lang-{code}.json")
    pack = json.load(open(p, encoding="utf-8"))
    ent = pack.get("entries", {})
    ent.update(EXTRA.get(code, {}))
    pack["entries"] = ent
    json.dump(pack, open(p, "w", encoding="utf-8"), ensure_ascii=False, indent=1)
    print(code, len(ent))
    total += len(ent)
print("TOTAL:", total)

# ---------- ۲) درون‌ریزی ادغامی در DB جاری (همان قاعدهٔ DbInit: بدون حذف) ----------
db = sqlite3.connect(os.path.join(ROOT, "src/Platform.Web/hr.db"))
n = 0
for code, title, d in LANGS:
    if not db.execute("select 1 from HrLangDefs where Code=?", (code,)).fetchone():
        db.execute("insert into HrLangDefs (Id, Code, Title, Dir, IsActive) values (?,?,?,?,1)",
                   (uuid.uuid4().hex, code, title, d))
    p = os.path.join(OUT, f"hr-lang-{code}.json")
    ent = json.load(open(p, encoding="utf-8"))["entries"]
    for k, v in ent.items():
        row = db.execute("select Id from HrLangEntries where LangCode=? and Key=?", (code, k)).fetchone()
        if row:
            db.execute("update HrLangEntries set Value=? where Id=?", (v, row[0]))
        else:
            db.execute("insert into HrLangEntries (Id, LangCode, Key, Value) values (?,?,?,?)",
                       (uuid.uuid4().hex, code, k, v))
        n += 1
db.commit()
print("DB upserted:", n)
for r in db.execute("select LangCode, count(*) from HrLangEntries group by LangCode"):
    print(r)
