# ---------- ۱) HrLang.cs — DictEn ----------
hl = open(SRC + "/Platform.Core/Services/HrLang.cs", encoding="utf-8").read()
i = hl.find("public static readonly Dictionary<string, string> DictEn")
j = hl.find("\n    };", i)
assert i > 0 and j > i
add_lines = []
cs_added = 0
for k, v in EN.items():
    key_cs = k.replace('"', '\\"')
    val_cs = v.replace('"', '\\"')
    entry = f'        ["{key_cs}"] = "{val_cs}",'
    if f'["{key_cs}"]' in hl:
        continue
    add_lines.append(entry)
    cs_added += 1
block = "\n        // ---------- فاز ۹۱ — ممیزی کامل چندزبانی: کلیدهای جاافتاده ----------\n" + "\n".join(add_lines) + "\n"
hl = hl[:j] + block + hl[j:]
open(SRC + "/Platform.Core/Services/HrLang.cs", "w", encoding="utf-8").write(hl)
print("DictEn added:", cs_added)

# ---------- ۲) DB جاری — en ----------
def unesc(s):
    return s.replace("\\n", "\n").replace('\\"', '"').replace("\\\\", "\\")
db = sqlite3.connect(SRC + "/Platform.Web/hr.db")
n = 0
for k, v in EN.items():
    ku = unesc(k)
    row = db.execute("select Id from HrLangEntries where LangCode='en' and Key=?", (ku,)).fetchone()
    if row:
        db.execute("update HrLangEntries set Value=? where Id=?", (v, row[0]))
    else:
        import uuid
        db.execute("insert into HrLangEntries (Id, LangCode, Key, Value) values (?,?,?,?)",
                   (uuid.uuid4().hex, "en", ku, v))
    n += 1
db.commit()
print("DB en upserted:", n)
