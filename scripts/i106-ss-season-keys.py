def main():
    con = sqlite3.connect(DB)
    cur = con.cursor()
    ins, skip = 0, 0
    for key, tr in KEYS.items():
        for lang, val in tr.items():
            row = cur.execute(
                "SELECT 1 FROM HrLangEntries WHERE LangCode=? AND Key=?", (lang, key)).fetchone()
            if row:
                skip += 1
                continue
            cur.execute(
                "INSERT INTO HrLangEntries (Id, LangCode, Key, Value) VALUES (?,?,?,?)",
                (uuid.uuid4().hex, lang, key, val))
            ins += 1
    con.commit()
    print(f"inserted={ins} skipped={skip}")
    for key in KEYS:
        n = cur.execute("SELECT COUNT(*) FROM HrLangEntries WHERE Key=?", (key,)).fetchone()[0]
        print(f"  langs={n}  {key[:50]}")

if __name__ == '__main__':
    main()
